"""10-сынып. Рекурсия

Рекурсия — функцияның өзін өзі шақыруы.
Тоқтау шарты болмаса, шақырулар жалғаса береді.

Іске қосу: python recursion_10.py

Оқушыға тапсырмалар:
1. san функциясындағы print жолын рекурсивті шақырудан кейін қойыңыз.
   Нәтижесі: 1 2 3 4 5 (әр сан бөлек жолда).
2. 1-ден n-ге дейінгі сандардың қосындысын рекурсиямен табыңыз.
   Тоқтау шарты: n == 0; қайтарылатын мән: 0.
   Тексеру: n=5 болса, жауап 15; n=0 болса, жауап 0.
3. n! факториалын рекурсиямен есептеңіз.
   Тоқтау шарты: n == 0; қайтарылатын мән: 1.
   Тексеру: n=5 болса, жауап 120; n=0 болса, жауап 1.

Тапсырмаларда n — 0 мен 100 арасындағы бүтін сан.
"""


def san(n):
    """n санынан 1-ге дейін шығару; 0 <= n <= 100."""
    if n == 0:
        return
    print(n)
    san(n - 1)


if __name__ == "__main__":
    print("Рекурсия мысалы: 5-тен 1-ге дейін")
    san(5)
